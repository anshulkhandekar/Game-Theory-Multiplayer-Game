import test from "node:test";
import assert from "node:assert/strict";
import { Game } from "../server/game.js";
test("loading remains frozen until all participating players continue and host counts down", () => {
  let now = 0;
  const g = new Game({ now: () => now });
  const a = g.join(null, "A"),
    b = g.join(null, "B");
  g.command("ready");
  g.command("start");
  now = 60000;
  g.tick(0.05);
  assert.equal(g.phase, "loading");
  assert.equal(g.worldTime, 0);
  assert.throws(() => g.acknowledgeLoad(a, g.round, true), /still loading/);
  assert.throws(() => g.command("countdown"), /Wait/);
  g.acknowledgeLoad(a, g.round);
  g.acknowledgeLoad(a, g.round, true);
  assert.throws(() => g.command("countdown"), /Wait/);
  g.acknowledgeLoad(b, g.round);
  g.acknowledgeLoad(b, g.round, true);
  g.command("countdown");
  assert.equal(g.snapshot().remaining, 8);
  now += 3000;
  g.tick(0.05);
  assert.equal(g.phase, "countdown");
  assert.equal(g.snapshot().remaining, 5);
  g.command("pause");
  now += 10000;
  g.tick(0.05);
  assert.equal(g.snapshot().remaining, 5);
  g.command("resume");
  now += 5000;
  g.tick(0.05);
  assert.equal(g.phase, "active");
});
test("reconnect clears loading readiness; stale acknowledgements cannot release the next round", () => {
  const g = new Game();
  const a = g.join(null, "A");
  g.command("ready");
  g.command("start");
  g.acknowledgeLoad(a, g.round);
  g.acknowledgeLoad(a, g.round, true);
  a.connected = false;
  assert.equal(g.join(a.token, "Other").id, a.id);
  assert.equal(a.loaded, false);
  assert.throws(() => g.command("countdown"), /Wait/);
  assert.throws(() => g.acknowledgeLoad(a, g.round - 1), /out of date/);
  const late = g.join(null, "Late");
  assert.equal(late.eligible, true);
  g.acknowledgeLoad(late, g.round);
  g.acknowledgeLoad(late, g.round, true);
  g.acknowledgeLoad(a, g.round);
  g.acknowledgeLoad(a, g.round, true);
  g.command("countdown");
  assert.equal(g.phase, "countdown");
});
test("a disconnected loading participant does not block the host", () => {
  const g = new Game();
  const a = g.join(null, "A"),
    b = g.join(null, "B");
  g.command("practice");
  g.acknowledgeLoad(a, g.round);
  g.acknowledgeLoad(a, g.round, true);
  b.connected = false;
  g.command("countdown");
  assert.equal(g.phase, "countdown");
  assert.equal(g.practice, true);
});
